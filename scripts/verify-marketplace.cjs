const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
    const output = path.resolve('storage/app/marketplace-qa');
    const browser = await chromium.launch({ headless: true, ...(process.env.LANDING_BROWSER ? { executablePath: process.env.LANDING_BROWSER } : {}) });
    const context = await browser.newContext();
    const page = await context.newPage();
    const errors = [], badAssets = [], requests = [], layouts = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => requests.push(request.url()));
    page.on('response', response => { if (/\/(build|dist)\//.test(response.url()) && response.status() >= 400) badAssets.push(response.url()); });
    await context.route('**/*', route => route.request().url().startsWith('http://127.0.0.1:8124/') ? route.continue() : route.abort());
    for (const width of [320, 360, 390, 768, 1440]) {
        await page.setViewportSize({ width, height: 1000 });
        await page.goto('http://127.0.0.1:8124/mercado');
        await page.waitForSelector('body.mp-js');
        await page.evaluate(() => window.scrollTo({ top: document.body.scrollHeight, behavior: 'instant' }));
        await page.waitForFunction(() => [...document.images].every(img => img.complete && img.naturalWidth));
        await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
        await page.waitForTimeout(500);
        const content = await page.evaluate(() => document.documentElement.scrollWidth);
        assert.ok(content <= width, `Overflow at ${width}: ${content}`);
        assert.equal(await page.getByRole('heading', { name: 'Encontre um despachante', exact: true }).count(), 1);
        assert.equal(await page.locator('input').count(), 7, 'Commodity search, supported filters and newsletter fields');
        await page.screenshot({ path: path.join(output, `marketplace-${width}.png`), fullPage: true });
        layouts.push({ width, content });
    }
    await page.setViewportSize({ width: 390, height: 844 });
    const toggle = page.locator('.mp-menu-toggle');
    await toggle.focus();
    assert.equal(await toggle.evaluate(el => getComputedStyle(el).outlineStyle), 'solid');
    await page.keyboard.press('Enter');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'true');
    assert.equal(await page.evaluate(() => document.activeElement.textContent), 'Plataforma');
    await page.keyboard.press('Escape');
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
    assert.equal(await page.evaluate(() => document.activeElement.className), 'mp-menu-toggle');
    await toggle.click();
    await page.locator('.mp-hero h1').click();
    assert.equal(await toggle.getAttribute('aria-expanded'), 'false');
    const login = await page.locator('.mp-mobile-nav .mp-button').getAttribute('href');
    const portal = await page.locator('.mp-mobile-nav .mp-portal-link').getAttribute('href');
    assert.match(login, /\/login$/);
    assert.match(portal, /\/portal-cliente\/Acesso$/);
    assert.equal(await page.locator('a[href="#"]').count(), 0);
    assert.match(await page.getByRole('link', { name: 'Falar com a equipa LogiGate' }).getAttribute('href'), /#contactos$/);
    const form = page.locator('.mp-newsletter');
    const email = page.locator('#newsletter-email');
    const button = page.getByRole('button', { name: 'Subscrever newsletter' });
    await email.fill('teste@example.test');
    await page.route('**/api/v1/newsletter/subscribe', route => route.fulfill({ status: 422, contentType: 'application/json', body: '{"success":false,"errors":{"email":["Email de teste rejeitado."]}}' }));
    await button.click();
    await page.waitForFunction(() => document.getElementById('newsletter-feedback').dataset.state === 'error');
    assert.equal(await email.getAttribute('aria-invalid'), 'true');
    assert.equal(await email.inputValue(), 'teste@example.test');
    await page.unroute('**/api/v1/newsletter/subscribe');
    let submissions = 0;
    await page.route('**/api/v1/newsletter/subscribe', async route => {
        submissions++;
        await new Promise(resolve => setTimeout(resolve, 400));
        await route.fulfill({ status: 200, contentType: 'application/json', body: '{"success":true}' });
    });
    await button.click();
    await page.waitForFunction(() => document.querySelector('.mp-newsletter').getAttribute('aria-busy') === 'true');
    await form.evaluate(el => el.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true })));
    assert.equal(await button.isDisabled(), true);
    await page.waitForFunction(() => document.getElementById('newsletter-feedback').dataset.state === 'success');
    assert.equal(submissions, 1);
    assert.equal(await email.inputValue(), '');
    await page.unroute('**/api/v1/newsletter/subscribe');
    await page.route('**/api/v1/newsletter/subscribe', route => route.abort());
    await email.fill('teste@example.test');
    await button.click();
    await page.waitForFunction(() => document.getElementById('newsletter-feedback').dataset.state === 'error');
    assert.match(await page.locator('#newsletter-feedback').textContent(), /confirmar o envio/);
    assert.equal(await button.isEnabled(), true);
    assert.equal(await email.inputValue(), 'teste@example.test');
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await page.locator('.mp-hero-copy').evaluate(el => getComputedStyle(el).animationName), 'none');
    assert.ok(!requests.some(url => url.includes('/api/v1/marketplace')));
    assert.deepEqual(errors, []);
    assert.deepEqual(badAssets, []);
    for (const mode of ['no-js', 'blocked-script']) {
        const fallback = await browser.newContext({ javaScriptEnabled: mode !== 'no-js', viewport: { width: 320, height: 844 } });
        await fallback.route('**/*', route => {
            const url = route.request().url();
            return !url.startsWith('http://127.0.0.1:8124/') || (mode === 'blocked-script' && /\.js$/.test(url)) ? route.abort() : route.continue();
        });
        const check = await fallback.newPage();
        await check.goto('http://127.0.0.1:8124/mercado');
        assert.equal(await check.locator('.mp-mobile-nav').isVisible(), true);
        assert.equal(await check.locator('.mp-unavailable').isVisible(), true);
        assert.ok(await check.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
        await fallback.close();
    }
    fs.writeFileSync(path.join(output, 'browser-results.json'), JSON.stringify({ layouts, pageErrors: errors, badAssets, checks: 'Empty catalogue, supported links, menu/keyboard/focus/Escape, newsletter validation/loading/success/network error/duplicate prevention, reduced motion, no JS, blocked JS: passed', blocked: 'Detailed public profile and direct provider contact routes are not available.' }, null, 2));
    await browser.close();
    console.log('Marketplace browser checks passed; screenshots and report in storage/app/marketplace-qa.');
})().catch(error => { console.error(error); process.exit(1); });
